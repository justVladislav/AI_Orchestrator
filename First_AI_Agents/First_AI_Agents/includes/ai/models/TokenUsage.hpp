#pragma once

#include <cstdint>

namespace ai::models {

/**
 * @brief Token accounting normalized across providers.
 *
 * Providers fill these counters only when their API returns usage data. Zero is
 * a valid "unknown/not reported" value for tests and providers without usage.
 *
 * MW-P2: inputTokens is deliberately the CONSERVATIVE TOTAL of every
 * input-side category a provider billed for a turn - plain input plus
 * cache-creation plus cache-read, when the provider reports the distinction
 * (Anthropic's prompt caching). It is never reduced by caching, so every
 * existing consumer that reads only inputTokens (MW-P0's
 * ProviderSessionBudgetGuard among them) keeps exactly its pre-caching
 * safety guarantee: caching can only make a Run cheaper, never look cheaper
 * to the budget than the tokens actually processed. cacheCreationInputTokens
 * and cacheReadInputTokens are the subset breakdown, present only for
 * accurate dollar-cost accounting (cache writes and cache reads are priced
 * differently from plain input) and Run Details projection - never a
 * separate spending authority.
 */
struct TokenUsage {
    struct CacheCreationDurationShare {
        // False is the explicit legacy/provider-unknown state. In that state
        // both detail counters must remain zero; duration is never inferred.
        bool known {false};
        std::uint64_t fiveMinuteTokens {0};
        std::uint64_t oneHourTokens {0};

    };

    /// Tokens consumed by the prompt/input side, including any cache
    /// creation/read subset reported below (see class comment).
    std::uint64_t inputTokens {0};

    /// Tokens generated by the model.
    std::uint64_t outputTokens {0};

    /// Subset of inputTokens written to the provider's prompt cache this
    /// turn (Anthropic: usage.cache_creation_input_tokens). Zero when the
    /// provider does not report cache usage or nothing was newly cached.
    std::uint64_t cacheCreationInputTokens {0};

    /// Subset of inputTokens served from the provider's prompt cache this
    /// turn (Anthropic: usage.cache_read_input_tokens). Zero when the
    /// provider does not report cache usage or nothing was served from cache.
    std::uint64_t cacheReadInputTokens {0};

    // ACD-2: the provider-reported duration partition of
    // cacheCreationInputTokens. Old rows and providers without detailed usage
    // stay explicitly unpartitioned.
    CacheCreationDurationShare cacheCreationDuration;

    /// True when both cache subsets actually fit into inputTokens - the
    /// invariant this class documents. A provider report that violates it
    /// (cache-read and/or cache-write larger than the whole input) is
    /// malformed: no consumer may trust its breakdown, grant it a cache
    /// discount, or price it as exact. Written as two subtractions so a value
    /// near the unsigned range can neither wrap a sum nor a difference.
    [[nodiscard]] constexpr bool cacheBreakdownIsConsistent() const noexcept
    {
        return cacheCreationInputTokens <= inputTokens
            && cacheReadInputTokens <= inputTokens - cacheCreationInputTokens;
    }

    /// The part of the totals above that comes from LONG-CONTEXT responses: those whose OWN
    /// inputTokens exceeded the model's long-context threshold (strictly greater), added in full -
    /// input, output and both cache categories. It is a SUBSET of every total counter and itself a
    /// consistent cache breakdown. It exists only to price an execution that mixes short and long
    /// responses exactly; it changes no token total and no provider budget.
    ///
    /// BACKEND-DERIVED ONLY: no provider adapter, parser or JSON ever fills it. The one writer is
    /// ai::application::accumulateResponseUsage(), which classifies each response itself and never
    /// trusts a partition that arrives on a response. All zero for a flat-priced model.
    struct LongContextShare {
        std::uint64_t inputTokens {0};
        std::uint64_t outputTokens {0};
        std::uint64_t cacheCreationInputTokens {0};
        std::uint64_t cacheReadInputTokens {0};

        // Backend-derived subset; ACD-3 populates it while aggregating each response.
        CacheCreationDurationShare cacheCreationDuration;

        [[nodiscard]] constexpr bool empty() const noexcept
        {
            return inputTokens == 0 && outputTokens == 0
                && cacheCreationInputTokens == 0 && cacheReadInputTokens == 0
                && !cacheCreationDuration.known
                && cacheCreationDuration.fiveMinuteTokens == 0
                && cacheCreationDuration.oneHourTokens == 0;
        }

        /// The same invariant as TokenUsage::cacheBreakdownIsConsistent(), for the partition.
        [[nodiscard]] constexpr bool cacheBreakdownIsConsistent() const noexcept
        {
            return cacheCreationInputTokens <= inputTokens
                && cacheReadInputTokens <= inputTokens - cacheCreationInputTokens;
        }

    };
    LongContextShare longContext;

    /// False once accumulating made this aggregate's accounting untrustworthy: a response that
    /// already carried a partition (a programming error - the partition is Backend-derived), a
    /// response whose own cache breakdown did not fit its input, or a counter that saturated at the
    /// unsigned maximum (its exact value is lost). Cost then reports priceKnown=false instead of an
    /// exact-looking number. Only the accumulator may invalidate it, and it is sticky: nothing ever
    /// sets it back to true.
    bool accountingTrusted {true};

};

} // namespace ai::models
