namespace ai::application {

// One shared contract for the provider schema and the Backend trust boundary.
// JSON Schema string lengths are character counts while these Backend limits
// are UTF-8 byte counts; enforcing both deliberately makes the Backend no less
// restrictive when a provider does not enforce the advertised schema.
inline constexpr std::string_view kProposalSubmissionSchemaVersion =
    "proposal-submission.v2";
inline constexpr std::size_t kProposalSubmissionMaxRawOutputBytes =
    16ULL * 1024 * 1024;
inline constexpr std::size_t kProposalSubmissionMaxSummaryBytes = 8192;
inline constexpr std::size_t kProposalSubmissionMaxChanges = 200;
inline constexpr std::size_t kProposalSubmissionMaxChangeIdBytes = 128;
inline constexpr std::size_t kProposalSubmissionMaxPathBytes = 4096;
inline constexpr std::size_t kProposalSubmissionMaxContentBytes =
    8ULL * 1024 * 1024;

// Trusted execution metadata that the Backend injects; never from model output.
// The parser places these values directly on the returned ProposedChangeSet so
// a model cannot forge its own identity or escalate its own permissions.
struct TrustedChangeSetMetadata {
    RunId runId;
    ProjectId projectId;
    ProviderId providerId;
    ModelId modelId;
    std::optional<ModelExecutionId> modelExecutionId;
    std::string agentRole;
    std::string baseRevision;  // trusted caller supplies; model suggestion ignored
    // See ProposedChangeSet::supersedesChangeSetId - set only by a repair
    // retry, pointing back at the attempt it replaced.
    std::optional<ChangeSetId> supersedesChangeSetId;
};

// Parses the raw text a model produced into a validated ProposedChangeSet.
//
// SECURITY BOUNDARY
//   - The model may not assign its own runId / projectId / providerId /
//     modelId / modelExecutionId.  The Backend provides those through
//     TrustedChangeSetMetadata.
//   - changeSetId is generated by the service layer; any value the model
//     embeds is ignored.
//   - A parse failure (malformed JSON, unrecognised enum, missing required
//     field, size limit exceeded) returns a Result failure with a stable
//     "proposal.*" error code.  Malformed output is NEVER stored as a
//     proposal.
//
// Accepted output formats:
//   1. A raw JSON object (the entire output is JSON, no surrounding text).
//   2. Exactly one ```json ... ``` code fence and nothing else.
//      Any prefix or suffix besides the fence is rejected.
class ProposedChangeSetParser {
public:
    // Returns a ProposedChangeSet in Received state on success.
    // Error codes:
    //   proposal.parse_error           – JSON could not be decoded
    //   proposal.extra_content         – prefix/suffix around the json fence
    //   proposal.multiple_fences       – more than one ```json fence found
    //   proposal.missing_field         – required field absent (top-level or
    //                                    per-change; see requireExactFields)
    //   proposal.unexpected_field      – an object carries a field outside its
    //                                    exact field set - this is how a
    //                                    provider/model that still sends the
    //                                    old expected_original_hash field is
    //                                    rejected; the field name itself is
    //                                    never echoed
    //   proposal.unsupported_schema    – schemaVersion is not
    //                                    kProposalSubmissionSchemaVersion
    //   proposal.invalid_operation     – unknown FileChangeOperation value
    //   proposal.invalid_field_type    – field has wrong JSON type
    //   proposal.invalid_field_value   – nullable field does not match its
    //                                    operation's null/string convention
    //   proposal.field_too_large       – a bounded string exceeds its Backend
    //                                    byte limit
    //   proposal.too_many_changes      – changes array exceeds limit
    //   proposal.empty_change_id       – a change entry has an empty changeId
    //   proposal.empty_summary         – summary field is empty or missing
    //
    // expected_original_hash is never accepted from provider/model output at
    // all (proposal-submission.v2): every ProposedFileChange returned here
    // has expectedOriginalHash == std::nullopt. The Backend fills it in from
    // an audited workspace_hash_file result before validation runs - see
    // AgentToolTurnLoopRunner::preflightTrustedHashes and
    // ChangeProposalService::bindObservedHashes().
    [[nodiscard]] static common::Result<ProposedChangeSet> parse(
        std::string_view rawModelOutput,
        const TrustedChangeSetMetadata& trustedMetadata);
};

} // namespace ai::application
